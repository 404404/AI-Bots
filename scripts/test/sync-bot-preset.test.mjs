import { readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { describe, expect, it } from 'vitest';
import {
  BOT_PRESET_DESCRIPTION,
  botPreset,
  PRODUCT_PATCHES,
  standardPresetSource,
  synced,
} from '../sync-bot-preset.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const sample = [
  '# header',
  '- insert:',
  '    - id: preset-standard',
  "      name: '@deepseek-ai/dsh-agent-preset'",
  '      config:',
  '        id: standard',
  '        order: 1',
  '        plugins:',
  '          - id: tool-bash',
  "            name: '@deepseek-ai/dsh-tool-bash'",
  "            disabled: !!js process.platform === 'win32'",
  '          - id: tool-ask-user',
  "            name: '@deepseek-ai/dsh-tool-ask-user'",
  '          - id: tool-todo',
  "            name: '@deepseek-ai/dsh-tool-todo'",
  '              - id: tool-subagent',
  "                name: '@deepseek-ai/dsh-tool-subagent'",
  '                config:',
  '                  provider: spawn',
  '              - id: tool-subagent-fork',
  "                name: '@deepseek-ai/dsh-tool-subagent'",
  '                config:',
  '                  provider: fork',
  '',
].join('\n');

describe('PersonaBot agent preset', () => {
  it('copies the standard preset and changes only its identity, order, question mode and native subagent tools', () => {
    expect(botPreset(sample)).toBe(
      [
        '- insert:',
        '    - id: preset-deepseekbot',
        "      name: '@deepseek-ai/dsh-agent-preset'",
        '      config:',
        '        id: deepseekbot',
        '        name: DeepSeekBot',
        `        description: '${BOT_PRESET_DESCRIPTION}'`,
        '        order: 5',
        '        plugins:',
        '          - id: tool-bash',
        "            name: '@deepseek-ai/dsh-tool-bash'",
        "            disabled: !!js process.platform === 'win32'",
        '          - id: tool-ask-user',
        "            name: '@deepseek-ai/dsh-tool-ask-user'",
        '            config:',
        '              mode: timed',
        '              timeout: 45',
        '          - id: tool-todo',
        "            name: '@deepseek-ai/dsh-tool-todo'",
        '              - id: tool-subagent',
        "                name: '@deepseek-ai/dsh-tool-subagent'",
        '                disabled: true',
        '                config:',
        '                  provider: spawn',
        '              - id: tool-subagent-fork',
        "                name: '@deepseek-ai/dsh-tool-subagent'",
        '                disabled: true',
        '                config:',
        '                  provider: fork',
      ].join('\n'),
    );
  });

  it('refuses a standard preset whose shape it does not recognise', () => {
    expect(() => botPreset(sample.replace('id: tool-ask-user', 'id: tool-ask'))).not.toThrow();
    expect(() =>
      botPreset(sample.replace("name: '@deepseek-ai/dsh-tool-ask-user'", "name: 'other'")),
    ).toThrow('Expected exactly one');
    expect(() => botPreset(sample.replace('        order: 1\n', ''))).toThrow(
      'Expected exactly one',
    );
  });

  it('rewrites only the generated region and is stable', () => {
    const before =
      'head\n# BEGIN generated by scripts/sync-bot-preset.mjs\nold\n# END generated by scripts/sync-bot-preset.mjs\ntail\n';
    const once = synced(before, sample);
    expect(once.startsWith('head\n# BEGIN generated')).toBe(true);
    expect(once.endsWith('# END generated by scripts/sync-bot-preset.mjs\ntail\n')).toBe(true);
    expect(once).toContain('id: preset-deepseekbot');
    expect(once).not.toContain('\nold\n');
    expect(synced(once, sample)).toBe(once);
  });

  it.each(['time-context', 'tool-schedule'])(
    'removes the complete %s block without modifying neighbors',
    (id) => {
      const block = [
        `          - id: ${id}`,
        `            name: '@deepseek-ai/dsh-${id}'`,
        '            config:',
        '              nested:',
        '                value: true',
        '',
        '            disabled: false',
        '            isolate:',
        '              clock: true',
      ].join('\n');
      const adjacent = '          - id: tool-ask-user';
      expect(botPreset(sample.replace(adjacent, `${block}\n${adjacent}`))).toBe(botPreset(sample));
      expect(botPreset(`${sample}${block}`)).toBe(botPreset(sample) + '\n');
    },
  );

  it('keeps the native preset loadable at the older supported floor', () => {
    const generated = botPreset(standardPresetSource(root));
    expect(generated).not.toContain('@deepseek-ai/dsh-time-context');
    expect(generated).not.toContain('@deepseek-ai/dsh-tool-schedule');
    expect(generated).not.toContain('{{cwd}}');
    expect(generated).toContain('@deepseek-ai/dsh-tool-fs');
    expect(botPreset(standardPresetSource(root))).toBe(generated);
  });

  it('keeps the committed product patch in sync with the installed DSH standard preset', () => {
    expect(PRODUCT_PATCHES).toEqual(['cordis.patch.yml', 'cordis.im.patch.yml']);
    for (const name of PRODUCT_PATCHES) {
      const committed = readFileSync(join(root, 'packages/deepseekbot', name), 'utf8');
      expect(synced(committed, standardPresetSource(root))).toBe(committed);
      expect(committed).toContain('agentPreset: deepseekbot');
      expect(committed).toContain('id: preset-deepseekbot');
    }
  });
});
