function escapeRegex(text) {
  return text.replace(/[.+^$()|[\]\\]/g, '\\$&');
}

export function globToRegExp(glob) {
  let out = '';
  for (let index = 0; index < glob.length; index += 1) {
    const char = glob[index];
    if (char === '*' && glob[index + 1] === '*') {
      if (glob[index + 2] === '/') {
        out += '(?:.*/)?';
        index += 2;
      } else {
        out += '.*';
        index += 1;
      }
    } else if (char === '*') out += '[^/]*';
    else if (char === '?') out += '[^/]';
    else if (char === '{') {
      const close = glob.indexOf('}', index);
      const options = glob.slice(index + 1, close).split(',');
      out += `(?:${options.map((option) => globToRegExp(option).source.slice(1, -1)).join('|')})`;
      index = close;
    } else out += escapeRegex(char);
  }
  return new RegExp(`^${out}$`);
}

const compiled = new Map();
export function matchesGlob(path, glob) {
  if (!compiled.has(glob)) compiled.set(glob, globToRegExp(glob));
  return compiled.get(glob).test(path);
}

export function classify(path, rules = RULES) {
  return rules.find((rule) => matchesGlob(path, rule.glob)) ?? null;
}

export function trackedFiles(root = ROOT) {
  return execFileSync('git', ['ls-files', '-z', '--cached', '--others', '--exclude-standard'], {
    cwd: root,
    encoding: 'utf8',
    maxBuffer: 1 << 26,
  })
    .split('\0')
    .filter(Boolean);
}

const CODE = /\.(?:[cm]?[jt]sx?)$/;
const STRING = /(['"`])((?:\\.|(?!\1)[^\\\n])*)\1/g;
const SPECIFIER = /(?:\bfrom\s*|\bimport\s*\(?\s*)(['"])([^'"]+)\1/g;

function directoriesOf(files) {
  const directories = new Set();
  for (const file of files) {
    let current = posix.dirname(file);
    while (current !== '.' && !directories.has(current)) {
      directories.add(current);
      current = posix.dirname(current);
    }
  }
  return directories;
}

export function createIndex(files, read) {
  const tracked = new Set(files);
  const directories = directoriesOf(files);
  const sources = new Map();
  const source = (file) => {
    if (!sources.has(file)) sources.set(file, read(file));
    return sources.get(file);
  };
  return { files, tracked, directories, source };
}

function normalize(path) {
  const joined = posix.normalize(path).replace(/\/+$/, '');
  return joined.startsWith('../') || joined === '..' ? null : joined;
}

export function pathReferences(index, file) {
  const references = new Set();
  const base = posix.dirname(file);
  for (const [, , literal] of index.source(file).matchAll(STRING)) {
    if (literal.includes('${') || literal.includes('://') || literal.startsWith('/')) continue;
    if (!literal.includes('/') && !/\.[a-z0-9]+$/i.test(literal)) continue;
    const trimmed = literal.replace(/^\.\//, '');
    for (const candidate of [normalize(posix.join(base, literal)), normalize(trimmed)]) {
      if (!candidate || candidate === '.') continue;
      if (index.tracked.has(candidate) || index.directories.has(candidate))
        references.add(candidate);
    }
  }
  return references;
}

function resolveSpecifier(index, from, specifier) {
  if (!specifier.startsWith('.')) return null;
  const target = normalize(posix.join(posix.dirname(from), specifier));
  if (!target) return null;
  const candidates = [target];
  for (const extension of ['.ts', '.tsx', '.mjs', '.js', '.json'])
    candidates.push(target + extension);
  if (/\.js$/.test(target))
    candidates.push(target.replace(/\.js$/, '.ts'), target.replace(/\.js$/, '.tsx'));
  for (const extension of ['/index.ts', '/index.tsx', '/index.mjs', '/index.js'])
    candidates.push(target + extension);
  return candidates.find((candidate) => index.tracked.has(candidate)) ?? null;
}

export function importClosure(index, entry) {
  const seen = new Set();
  const queue = [entry];
  while (queue.length) {
    const file = queue.pop();
    if (seen.has(file) || !index.tracked.has(file)) continue;
    seen.add(file);
    if (!CODE.test(file)) continue;
    for (const [, , specifier] of index.source(file).matchAll(SPECIFIER)) {
      const resolved = resolveSpecifier(index, file, specifier);
      if (resolved) queue.push(resolved);
    }
  }
  return seen;
}

function covers(reference, path) {
  return path === reference || path.startsWith(`${reference}/`);
}

export function referenceMap(index) {
  const map = new Map();
  for (const file of index.files) {
    if (!CODE.test(file) || !TEST_AREAS.some((glob) => matchesGlob(file, glob))) continue;
    const references = [...pathReferences(index, file)];
    if (!references.length) continue;
    const expanded = new Set(references);
    for (const reference of references)
      if (CODE.test(reference))
        for (const imported of importClosure(index, reference)) expanded.add(imported);
    map.set(file, expanded);
  }
  return map;
}

export function referencingFiles(map, paths) {
  const found = new Set();
  for (const [file, references] of map)
    for (const reference of references)
      if (paths.some((path) => covers(reference, path))) found.add(file);
  return [...found].sort();
}

export function docsSiteInputs(index) {
  const inputs = new Set();
  for (const entry of DOCS_SITE_ENTRIES)
    for (const file of importClosure(index, entry)) inputs.add(file);
  return inputs;
}

export function parseChanges(text) {
  return text
    .split('\n')
    .filter((line) => line.trim())
    .map((line) => {
      const [status, path, previous] = line.split('\t');
      return { status: status.trim().toLowerCase(), path, previous: previous || undefined };
    });
}

const REMOVED = new Set(['removed', 'renamed', 'd', 'r']);
const statusOf = (status) =>
  REMOVED.has(status) ? status : status.slice(0, 1) === 'r' ? 'r' : status;

export function plan({ event, labels = [], changes = [], truncated = false, index }) {
  const result = (tests, reason, extra = {}) => ({
    tests,
    docsSite: tests === 'full',
    reason,
    related: [],
    ...extra,
  });
  if (event !== 'pull_request') return result('full', `${event} always runs the full suite`);
  if (labels.includes(FULL_LABEL))
    return result('full', `the ${FULL_LABEL} label asks for a full run`);
  if (truncated || changes.length >= MAX_CHANGED_FILES)
    return result('full', 'the changed file list is too long to select from');

  const paths = [];
  let docsSite = false;
  let docsReason = '';
  const docsInputs = docsSiteInputs(index);
  for (const change of changes) {
    for (const path of [change.path, change.previous].filter(Boolean)) {
      const rule = classify(path);
      if (!rule) return result('full', `${path} matches no rule in scripts/ci-plan.mjs`);
      if (rule.tests === 'full') return result('full', `${path} is a full-run input (${rule.why})`);
      if (rule.tests === 'related' && REMOVED.has(statusOf(change.status)) && CODE.test(path))
        return result('full', `${path} was removed or renamed, so its importers cannot be traced`);
      if (!docsSite && (rule.docsSite || docsInputs.has(path))) {
        docsSite = true;
        docsReason = path;
      }
      paths.push({ path, rule });
    }
  }

  const changedPaths = paths.map(({ path }) => path);
  const referencing = referencingFiles(referenceMap(index), changedPaths);
  if (!docsSite && referencing.includes(DOCS_SITE_TEST)) {
    docsSite = true;
    docsReason = DOCS_SITE_TEST;
  }
  const inputs = new Set(referencing);
  for (const { path, rule } of paths)
    if (rule.tests === 'related' && index.tracked.has(path)) inputs.add(path);
  inputs.delete(DOCS_SITE_TEST);
  const related = [...inputs].sort();
  const docsNote = docsSite ? `; docs site built for ${docsReason}` : '';
  if (!related.length)
    return {
      tests: 'none',
      docsSite,
      reason: `no changed file can affect a test${docsNote}`,
      related,
    };
  return {
    tests: 'affected',
    docsSite,
    reason: `${related.length} changed or referencing files select related tests${docsNote}`,
    related,
  };
}

export function parseGitChanges(text) {
  return text
    .split('\n')
    .filter((line) => line.trim())
    .map((line) => {
      const [status, first, second] = line.split('\t');
      const code = status[0].toLowerCase();
      return second
        ? { status: code, path: second, previous: first }
        : { status: code, path: first };
    });
}

export function gitChanges(base, root = ROOT) {
  const git = (...args) => execFileSync('git', args, { cwd: root, encoding: 'utf8' });
  const mergeBase = git('merge-base', base, 'HEAD').trim();
  const changes = parseGitChanges(git('diff', '--name-status', '-M', mergeBase));
  for (const path of git('ls-files', '--others', '--exclude-standard').split('\n').filter(Boolean))
    changes.push({ status: 'a', path });
  return changes;
}

export function rulesTable(rules = RULES) {
  const mode = { full: 'Full suite', related: 'Related tests', none: 'No tests of its own' };
  const header = ['Path', 'Pull request runs', 'Docs site', 'Why'];
  const body = rules.map((rule) => [
    `\`${rule.glob}\``,
    mode[rule.tests],
    rule.docsSite ? 'Yes' : '',
    rule.why,
  ]);
  const widths = header.map((_, column) =>
    Math.max(3, ...[header, ...body].map((row) => row[column].length)),
  );
  const line = (cells) =>
    `| ${cells.map((cell, column) => cell.padEnd(widths[column])).join(' | ')} |`;
  return [
    TABLE_BEGIN,
    '',
    line(header),
    line(widths.map((width) => '-'.repeat(width))),
    ...body.map(line),
    '',
    TABLE_END,
  ].join('\n');
}

export function syncGuide(text) {
  const start = text.indexOf(TABLE_BEGIN);
  const end = text.indexOf(TABLE_END);
  if (start < 0 || end < start) throw new Error(`${GUIDE} has no generated CI plan table`);
  return text.slice(0, start) + rulesTable() + text.slice(end + TABLE_END.length);
}

export function checkClassification(files, rules = RULES) {
  const problems = [];
  for (const file of files)
    if (!classify(file, rules))
      problems.push(`${file} matches no rule; classify it in RULES in scripts/ci-plan.mjs`);
  for (const rule of rules)
    if (!files.some((file) => matchesGlob(file, rule.glob)))
      problems.push(
        `Rule ${rule.glob} matches no tracked file; remove or correct it in scripts/ci-plan.mjs`,
      );
  return problems;
}

export function checkTestInclude(files, include) {
  const problems = [];
  for (const file of files) {
    if (!/\.test\.[cm]?[jt]sx?$/.test(file) || file.includes('/fixtures/')) continue;
    if (!include.some((glob) => matchesGlob(file, glob)))
      problems.push(`${file} is a test outside the Vitest include in vitest.config.ts`);
  }
  if (!files.includes(DOCS_SITE_TEST))
    problems.push(`DOCS_SITE_TEST ${DOCS_SITE_TEST} does not exist`);
  for (const entry of DOCS_SITE_ENTRIES)
    if (!files.includes(entry)) problems.push(`Docs site entry ${entry} does not exist`);
  return problems;
}

export function checkWorkflow(workflow) {
  const problems = [];
  const jobs = workflow?.jobs ?? {};
  const aggregate = jobs.verify;
  const triggers = workflow?.on ?? {};
  if (!aggregate) return [`${WORKFLOW} has no aggregate verify job`];
  if (aggregate.name !== REQUIRED_CHECK)
    problems.push(`The aggregate job must keep the required check name "${REQUIRED_CHECK}"`);
  if (!String(aggregate.if ?? '').includes('always()'))
    problems.push('The aggregate job must run with if: always() so skipped jobs still report');
  const needs = [aggregate.needs ?? []].flat();
  for (const job of Object.keys(jobs))
    if (job !== 'verify' && !needs.includes(job))
      problems.push(`The aggregate job does not need ${job}`);
  for (const [event, config] of Object.entries(triggers))
    if (config && (config.paths || config['paths-ignore']))
      problems.push(
        `The ${event} trigger filters paths; path selection belongs to scripts/ci-plan.mjs`,
      );
  for (const event of ['pull_request', 'push', 'schedule', 'workflow_dispatch'])
    if (!(event in triggers)) problems.push(`${WORKFLOW} must run on ${event}`);
  if (!triggers.pull_request?.types?.includes('labeled'))
    problems.push(`pull_request must include the labeled type so ${FULL_LABEL} starts a full run`);
  const shards = jobs['test-full']?.strategy?.matrix?.shard;
  if (!Array.isArray(shards) || shards.length !== SHARDS)
    problems.push(`test-full must run a matrix of ${SHARDS} shards to match SHARDS`);
  return problems;
}

export async function check(root = ROOT) {
  const { parse } = await import('yaml');
  const config = (await import(pathToFileURL(join(root, 'vitest.config.ts')).href)).default;
  const files = trackedFiles(root).filter((file) => existsSync(join(root, file)));
  const guide = readFileSync(join(root, GUIDE), 'utf8');
  const problems = [
    ...checkClassification(files),
    ...checkTestInclude(files, config.test.include),
    ...checkWorkflow(parse(readFileSync(join(root, WORKFLOW), 'utf8'))),
  ];
  if (syncGuide(guide) !== guide)
    problems.push(`${GUIDE} CI plan table is stale; run node scripts/ci-plan.mjs --write`);
  return problems;
}

export function androidNativeTests(tests, changes) {
  return (
    tests === 'full' ||
    changes.some((change) =>
      [change.path, change.previous].some((path) => path?.startsWith('apps/mobile/modules/')),
    )
  );
}

function githubPlan(changesFile) {
  const event = process.env.GITHUB_EVENT_NAME;
  const payload = JSON.parse(readFileSync(process.env.GITHUB_EVENT_PATH, 'utf8'));
  const labels = (payload.pull_request?.labels ?? []).map((label) => label.name);
  const text = changesFile && existsSync(changesFile) ? readFileSync(changesFile, 'utf8') : '';
  const changes = parseChanges(text);
  const changedCount = payload.pull_request?.changed_files ?? changes.length;
  const files = trackedFiles();
  const index = createIndex(files, (file) => readFileSync(join(ROOT, file), 'utf8'));
  const result = plan({ event, labels, changes, truncated: changedCount > changes.length, index });
  appendFileSync(
    process.env.GITHUB_OUTPUT,
    `tests=${result.tests}\ndocs-site=${result.docsSite}\nandroid-native=${androidNativeTests(result.tests, changes)}\nrelated=${JSON.stringify(result.related)}\n`,
  );
  const listed = result.related.map((file) => `- \`${file}\``).join('\n');
  appendFileSync(
    process.env.GITHUB_STEP_SUMMARY,
    `### CI test plan: ${result.tests}\n\n${result.reason}.\n\nDocs site build: ${result.docsSite ? 'yes' : 'no'}\n\n${listed ? `Related test inputs:\n\n${listed}\n` : ''}`,
  );
  console.log(JSON.stringify(result, null, 2));
}

function localPlan(base) {
  const changes = gitChanges(base);
  const files = [...new Set([...trackedFiles(), ...changes.map((change) => change.path)])].filter(
    (file) => existsSync(join(ROOT, file)),
  );
  const index = createIndex(files, (file) => readFileSync(join(ROOT, file), 'utf8'));
  const result = plan({ event: 'pull_request', changes, index });
  console.log(`${result.tests}: ${result.reason}`);
  if (result.tests === 'full') console.log(`pnpm vitest run --exclude ${DOCS_SITE_TEST}`);
  if (result.tests === 'affected')
    console.log(
      `pnpm vitest related --run --passWithNoTests --exclude ${DOCS_SITE_TEST} ${result.related.join(' ')}`,
    );
  if (result.docsSite) console.log(`pnpm slides:build && pnpm vitest run ${DOCS_SITE_TEST}`);
}

if (
  process.argv[1] &&
  realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))
) {
  const args = process.argv.slice(2);
  const option = (name) => {
    const at = args.indexOf(name);
    return at < 0 ? undefined : args[at + 1];
  };
  if (args.includes('--check')) {
    const problems = await check();
    if (problems.length) {
      console.error(problems.join('\n'));
      process.exit(1);
    }
  } else if (args.includes('--write')) {
    const path = join(ROOT, GUIDE);
    writeFileSync(path, syncGuide(readFileSync(path, 'utf8')));
  } else if (args.includes('--github')) {
    githubPlan(option('--changes'));
  } else {
    localPlan(option('--base') ?? 'origin/main');
  }
}
