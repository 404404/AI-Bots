import { readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'packages', 'deepseekbot', 'cordis.patch.yml');
const BEGIN = '# BEGIN generated by scripts/sync-bot-preset.mjs';
const END = '# END generated by scripts/sync-bot-preset.mjs';
export const BOT_PRESET_ID = 'deepseekbot';
export const QUESTION_WAIT_SECONDS = 45;

function replaceOnce(text, from, to) {
  if (text.split(from).length !== 2)
    throw new Error(`Expected exactly one ${JSON.stringify(from)} in the standard preset`);
  return text.replace(from, to);
}

export function standardPresetSource(from = root) {
  const dsh = realpathSync(join(from, 'node_modules', '@deepseek-ai', 'dsh'));
  const webApp = createRequire(join(dsh, 'package.json')).resolve(
    '@deepseek-ai/dsh-web-app/package.json',
  );
  return readFileSync(join(dirname(webApp), 'presets', 'standard.patch.yml'), 'utf8');
}

export function botPreset(standard) {
  const rows = standard.split('\n');
  const first = rows.findIndex((row) => row.startsWith('- insert:'));
  if (first < 0) throw new Error('The standard preset has no insert list');
  let body = rows.slice(first).join('\n').trimEnd();
  body = replaceOnce(body, 'id: preset-standard\n', `id: preset-${BOT_PRESET_ID}\n`);
  body = replaceOnce(body, '        id: standard\n', `        id: ${BOT_PRESET_ID}\n`);
  body = replaceOnce(body, '        order: 1\n', '        order: 5\n');
  const ask = "            name: '@deepseek-ai/dsh-tool-ask-user'\n";
  body = replaceOnce(
    body,
    ask,
    `${ask}            config:\n              mode: timed\n              timeout: ${QUESTION_WAIT_SECONDS}\n`,
  );
  return body;
}

export function generatedRegion(standard) {
  return [
    BEGIN,
    '# The PersonaBot agent preset: DSH standard, with ask_user_question in timed',
    '# mode so a pending question does not hold the Bot (ADR-0187). Do not edit;',
    '# run `node scripts/sync-bot-preset.mjs` after a DSH upgrade.',
    botPreset(standard),
    END,
  ].join('\n');
}

export function synced(current, standard) {
  const start = current.indexOf(BEGIN);
  const end = current.indexOf(END);
  if (start < 0 || end < start) throw new Error('The product patch has no generated preset region');
  return current.slice(0, start) + generatedRegion(standard) + current.slice(end + END.length);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const current = readFileSync(target, 'utf8');
  const next = synced(current, standardPresetSource());
  if (process.argv.includes('--check')) {
    if (next !== current) {
      console.error(
        'packages/deepseekbot/cordis.patch.yml is out of sync with the DSH standard preset; run node scripts/sync-bot-preset.mjs',
      );
      process.exit(1);
    }
    console.log('The PersonaBot agent preset matches the DSH standard preset.');
  } else {
    writeFileSync(target, next);
    console.log('Wrote the PersonaBot agent preset.');
  }
}
