import { readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const PRODUCT_PATCHES = ['cordis.patch.yml', 'cordis.im.patch.yml'];
const BEGIN = '# BEGIN generated by scripts/sync-bot-preset.mjs';
const END = '# END generated by scripts/sync-bot-preset.mjs';
export const BOT_PRESET_ID = 'deepseekbot';
export const QUESTION_WAIT_SECONDS = 45;
export const BOT_PRESET_DESCRIPTION =
  'PersonaBot 默认模式：与标准模式相同，但提问卡超过 45 秒未回答时 Bot 会继续处理其他消息，Subagent 改用 Bot 自己的 bot_subagent 工具。 The PersonaBot default: the standard mode, except that a question card left unanswered for 45 seconds no longer holds the Bot, and Subagents run through bot_subagent.';
export const BOT_DISABLED_PLUGINS = ['tool-subagent', 'tool-subagent-fork'];

function replaceOnce(text, from, to) {
  if (text.split(from).length !== 2)
    throw new Error(`Expected exactly one ${JSON.stringify(from)} in the standard preset`);
  return text.replace(from, to);
}

export function standardPresetSource(from = root) {
  const dsh = realpathSync(join(from, 'node_modules', '@deepseek-ai', 'dsh'));
  const webApp = createRequire(join(dsh, 'package.json')).resolve(
    '@deepseek-ai/dsh-web-app/package.json',
  );
  return readFileSync(join(dirname(webApp), 'presets', 'standard.patch.yml'), 'utf8');
}

export function botPreset(standard) {
  const rows = standard.split('\n');
  const first = rows.findIndex((row) => row.startsWith('- insert:'));
  if (first < 0) throw new Error('The standard preset has no insert list');
  let body = rows.slice(first).join('\n').trimEnd();
  body = replaceOnce(body, 'id: preset-standard\n', `id: preset-${BOT_PRESET_ID}\n`);
  body = replaceOnce(
    body,
    '        id: standard\n',
    `        id: ${BOT_PRESET_ID}\n        name: DeepSeekBot\n        description: '${BOT_PRESET_DESCRIPTION}'\n`,
  );
  body = replaceOnce(body, '        order: 1\n', '        order: 5\n');
  const ask = "            name: '@deepseek-ai/dsh-tool-ask-user'\n";
  body = replaceOnce(
    body,
    ask,
    `${ask}            config:\n              mode: timed\n              timeout: ${QUESTION_WAIT_SECONDS}\n`,
  );
  for (const id of BOT_DISABLED_PLUGINS) {
    const row = `              - id: ${id}\n                name: '@deepseek-ai/dsh-tool-subagent'\n`;
    body = replaceOnce(body, row, `${row}                disabled: true\n`);
  }
  body = body.replace(
    /          - id: (?:time-context|tool-schedule)\n            name: '[^']+'\n/g,
    '',
  );
  const persona = "            name: '@deepseek-ai/dsh-persona'\n            config:\n";
  if (body.includes(persona) && !body.includes('suffix: Your working directory'))
    body = body.replace(
      persona,
      `${persona}              suffix: Your working directory is {{cwd}}.\n`,
    );
  return body;
}

export function generatedRegion(standard) {
  return [
    BEGIN,
    '# The PersonaBot agent preset: DSH standard, with ask_user_question in timed',
    '# mode so a pending question does not hold the Bot (ADR-0187) and without the',
    '# native subagent tools the Bot replaces with bot_subagent. Do not edit;',
    '# run `node scripts/sync-bot-preset.mjs` after a DSH upgrade.',
    botPreset(standard),
    END,
  ].join('\n');
}

export function synced(current, standard) {
  const start = current.indexOf(BEGIN);
  const end = current.indexOf(END);
  if (start < 0 || end < start) throw new Error('The product patch has no generated preset region');
  return current.slice(0, start) + generatedRegion(standard) + current.slice(end + END.length);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const standard = standardPresetSource();
  const stale = [];
  for (const name of PRODUCT_PATCHES) {
    const target = join(root, 'packages', 'deepseekbot', name);
    const current = readFileSync(target, 'utf8');
    const next = synced(current, standard);
    if (next === current) continue;
    stale.push(name);
    if (!process.argv.includes('--check')) writeFileSync(target, next);
  }
  if (process.argv.includes('--check') && stale.length > 0) {
    console.error(
      `packages/deepseekbot/${stale.join(', ')} is out of sync with the DSH standard preset; run node scripts/sync-bot-preset.mjs`,
    );
    process.exit(1);
  }
  console.log(
    stale.length > 0
      ? `Wrote the PersonaBot agent preset to ${stale.join(', ')}.`
      : 'The PersonaBot agent preset matches the DSH standard preset.',
  );
}
